// Shared output step for the figure builds: a standalone page per theme (for checking in a
// browser) and a script module that the app bundles (card markup + mount(root)).
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import * as k from "../vendor/anatomy/kit/iso-kit.mjs";
import * as lathe from "../vendor/anatomy/kit/lathe.mjs";
import { kitScript } from "../vendor/anatomy/scripts/inline-kit.mjs";

const FIGURES = join(dirname(fileURLToPath(import.meta.url)), "..");

/** The lathe module (round parts and prisms on any axis) as inlineable source. */
export function latheScript() {
  return readFileSync(join(FIGURES, "vendor/anatomy/kit/lathe.mjs"), "utf8")
    .replace(/^import .*$/m, "")
    .replace(/^export /gm, "");
}

export function emit({ dir, name, global, title, cardHtml, live, withLathe = false }) {
  // with the lathe, parts code reaches both modules as k.* and G.*, as it does at build time
  const names = (mod) => Object.keys(mod).join(", ");
  // the lathe goes in its own scope: it redeclares a few helper names that the kit also has
  const kit = kitScript() + (withLathe ? `\nconst k = { ${names(k)} };\nconst G = (() => {\n${latheScript()}\nreturn { ${names(lathe)} };\n})();` : "");
  const pages = {};
  for (const theme of ["dark", "light"]) {
    const script = `${kit}\n${live}\nmount(document.querySelector(".iso-figure"));`;
    const file = join(dir, `${name}${theme === "light" ? "-light" : ""}.html`);
    writeFileSync(file, k.pageHtml({ title, theme, body: cardHtml, script }));
    pages[theme] = file;
  }
  const mod = `/* ${title} (generated by figures/${name}/build.mjs) */\nconst ${global} = (() => {\n${kit}\n${live}\nreturn { card: ${JSON.stringify(cardHtml)}, mount };\n})();\n`;
  mkdirSync(join(FIGURES, "dist"), { recursive: true });
  writeFileSync(join(FIGURES, "dist", `${name}.js`), mod);
  return pages;
}
